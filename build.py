"""Build the static site into dist/.

    python build.py

Output is plain static files plus header rules in two forms:
  dist/_headers       Netlify / Cloudflare Pages syntax
  dist/headers.json   used by serve.py (and easy to translate for nginx etc.)
"""
import json
import os
import shutil

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, "src")
DIST = os.path.join(ROOT, "dist")

PYODIDE_VERSION = "314.0.7"
PYODIDE_INDEX = f"https://cdn.jsdelivr.net/pyodide/v{PYODIDE_VERSION}/full/"

STATIC = ["index.html", "theme.js", "app.js", "app.css", "icon.svg", "sandbox.html", "vendor", "wheels"]

# The app page: no network beyond its own origin, can't be framed.
APP_CSP = "; ".join([
    "default-src 'none'",
    "script-src 'self'",
    # Hashes, not 'unsafe-inline': the empty-string hash admits only the empty
    # <style> marker that stops Plotly injecting styles (vendor/plotly.css
    # provides them); 'unsafe-hashes' + the second hash admits only Plotly's
    # fixed "image-rendering: …pixelated" attribute used for heatmap pixels.
    "style-src 'self' 'sha256-47DEQpj8HBSa+/TImW+5JCeuQeRkm5NMpJWZG3hSuFU=' 'unsafe-hashes' 'sha256-AR/cKIZjWPcPmBUPDA6oti9XBiTbJvz0Cro2J1VzzS8='",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    "connect-src 'self'",
    "frame-src 'self'",
    "worker-src 'none'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
])

# The Python sandbox: opaque origin (CSP sandbox, in addition to the iframe
# attribute), may only fetch the pinned Pyodide distribution, and may only be
# framed by the app's own origin.
SANDBOX_CSP = "; ".join([
    "default-src 'none'",
    f"script-src 'self' {PYODIDE_INDEX} blob: 'wasm-unsafe-eval'",
    "worker-src blob:",
    f"connect-src {PYODIDE_INDEX}",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'self'",
    "sandbox allow-scripts",
])

COMMON = {
    "X-Content-Type-Options": "nosniff",
    "Referrer-Policy": "no-referrer",
    "Cross-Origin-Opener-Policy": "same-origin",
    "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()",
}

HEADERS = [
    ("/*", COMMON),
    ("/", {"Content-Security-Policy": APP_CSP}),
    ("/index.html", {"Content-Security-Policy": APP_CSP}),
    ("/sandbox.html", {"Content-Security-Policy": SANDBOX_CSP}),
]


def read(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return f.read()


def build():
    if os.path.exists(DIST):
        shutil.rmtree(DIST)
    os.makedirs(DIST)
    for name in STATIC:
        src = os.path.join(SRC, name)
        dst = os.path.join(DIST, name)
        if os.path.isdir(src):
            shutil.copytree(src, dst)
        else:
            shutil.copy2(src, dst)

    # The sandbox has an opaque origin, so it can't fetch worker/python sources
    # from us; embed them in its script instead.
    prelude = (
        "/* generated by build.py */\n"
        f"const PYODIDE_INDEX = {json.dumps(PYODIDE_INDEX)};\n"
        f"const WORKER_SOURCE = {json.dumps(read('worker.js'))};\n"
        f"const PY_SOURCE = {json.dumps(read('explorer.py'))};\n"
    )
    with open(os.path.join(DIST, "sandbox.js"), "w", encoding="utf-8") as f:
        f.write(prelude + read("sandbox.js"))

    with open(os.path.join(DIST, "_headers"), "w") as f:
        for path, hdrs in HEADERS:
            f.write(path + "\n")
            for k, v in hdrs.items():
                f.write(f"  {k}: {v}\n")
    with open(os.path.join(DIST, "headers.json"), "w") as f:
        json.dump(HEADERS, f, indent=2)
    print(f"built {DIST} (Pyodide {PYODIDE_VERSION})")


if __name__ == "__main__":
    build()
