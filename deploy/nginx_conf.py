"""Write the production nginx.conf, with the security headers taken from build.py.

    python deploy/nginx_conf.py > nginx.conf

Every page needs a password (deploy/auth.js) except the sandbox's two files: the
sandbox has an opaque origin, so the browser may not send the password with its
requests. They hold only the app's code, which is public anyway.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from build import HEADERS  # noqa: E402

COMMON = dict(HEADERS)["/*"]
CSP = {path: h["Content-Security-Policy"] for path, h in HEADERS if path != "/*"}
REALM = "Data browser"

MAIN = r"""# Generated by deploy/nginx_conf.py. Don't edit: change build.py or that script.
load_module modules/ngx_http_js_module.so;

worker_processes 1;
pid /tmp/nginx.pid;
error_log /dev/stderr warn;
env SITE_PASSWORD;

events {
    worker_connections 512;
}

http {
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    server_tokens off;
    sendfile on;
    gzip on;
    gzip_types text/css text/javascript application/javascript application/json image/svg+xml;

    client_body_temp_path /tmp/client_body;
    proxy_temp_path /tmp/proxy;
    fastcgi_temp_path /tmp/fastcgi;
    uwsgi_temp_path /tmp/uwsgi;
    scgi_temp_path /tmp/scgi;

    js_import auth from /etc/nginx/auth.js;
    js_set $authorised auth.authorised;

    # Paths only vulnerability scanners ask for.
    map $request_uri $probe {
        default 0;
        "~*\.(env|git|aws|ssh|htaccess)\b|wp-(admin|login|content|includes)|xmlrpc|\.php\b|phpmyadmin|cgi-bin|/actuator|/boaform|/HNAP1|\.\./|etc/passwd" 1;
    }
    # A request that sent a password and was refused.
    map "$probe:$status:$http_authorization" $security_event {
        "~^1:" probe;
        "~^0:401:.+" wrong_password;
        default "";
    }

    # One `SECURITY {json}` line on stderr per event. ~/Projects/security-log.sh collects them.
    log_format security escape=json
        'SECURITY {"event":"$security_event","ip":"$http_cf_connecting_ip","country":"$http_cf_ipcountry",'
        '"method":"$request_method","path":"$request_uri","ua":"$http_user_agent","status":"$status"}';
    log_format main '$http_cf_connecting_ip "$request" $status $body_bytes_sent "$http_user_agent"';

    server {
        listen 80;
        server_name _;
        root /usr/share/nginx/html;
        index index.html;

        access_log /dev/stdout main;
        access_log /dev/stderr security if=$security_event;

        location = /healthz {
            access_log off;
            return 204;
        }

%(locations)s
    }
}
"""


def headers(extra):
    lines = [f'add_header {k} "{v}" always;' for k, v in {**COMMON, **extra}.items()]
    lines.append('add_header Cache-Control "no-cache" always;')
    return lines


def location(match, extra, protected=True, body=()):
    lines = []
    if protected:
        lines += [
            'if ($authorised = "") {',
            f'    add_header WWW-Authenticate \'Basic realm="{REALM}", charset="UTF-8"\' always;',
            "    return 401;",
            "}",
        ]
    lines += headers(extra) + list(body)
    inner = "\n".join("            " + l for l in lines)
    return f"        location {match} {{\n{inner}\n        }}\n"


def render():
    locations = "\n".join([
        location("= /", {"Content-Security-Policy": CSP["/"]}, body=["try_files /index.html =404;"]),
        location("= /index.html", {"Content-Security-Policy": CSP["/index.html"]}),
        location("= /sandbox.html", {"Content-Security-Policy": CSP["/sandbox.html"]}, protected=False),
        location("= /sandbox.js", {}, protected=False),
        location("/", {}, body=["try_files $uri =404;"]),
    ])
    return MAIN % {"locations": locations}


if __name__ == "__main__":
    sys.stdout.write(render())
